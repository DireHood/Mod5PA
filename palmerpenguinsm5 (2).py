# Math import for function
import math

# Constants representing the species and count
SP_CHINSTRAP = "Chinstrap"
SP_GENTOO = "Gentoo"
SP_ADELIE = "Adelie"
NUM_CHINSTRAP = 68
NUM_GENTOO = 123
NUM_ADELIE = 151

# Store the penguin species names and their observation counts in matching lists
species_names = [SP_CHINSTRAP,
                 SP_GENTOO,
                 SP_ADELIE]

species_counts = [NUM_CHINSTRAP,
                  NUM_GENTOO,
                  NUM_ADELIE]

total_species = len(species_names)
largest_count = max(species_counts)
smallest_count = min(species_counts)
largest_index = species_counts.index(largest_count)
smallest_index = species_counts.index(smallest_count)
largest_species = species_names[largest_index]
smallest_species = species_names[smallest_index]
total_penguins = sum(species_counts)
average_penguins = total_penguins / total_species

chinstrap_percent = species_counts[0] / total_penguins * 100
gentoo_percent = species_counts[1] / total_penguins * 100
adelie_percent = species_counts[2] / total_penguins * 100

species_percentages = [
    chinstrap_percent,
    gentoo_percent,
    adelie_percent
]

average_penguins_rounded_up = math.ceil(average_penguins)

# Output the species names with introductory text
print("Introducing the Palmer Penguins:")
print(f"\t{species_names[0]}!")
print(f"\t{species_names[1]}!")
print("and last but not least. . .")
print(f"\t{species_names[2]}!")
print()

print(f"There are a total of {total_species} penguin species in this dataset.")
print()

# Display the total number of penguins alongside the average penguins per species
print(f"There are a total of {total_penguins} penguins in the dataset")
print(f"The average number of penguins per species is ({average_penguins:.1f}).")
print(f"The average rounded up is {average_penguins_rounded_up} penguins.")
print()

# Display the species counts alongside their percentages
for index, species in enumerate(species_names):
    print(f"{species}: {species_counts[index]} "
          f"({species_percentages[index]:.2f}%)")

print()

print(f"The species with the most observations is {largest_species} "
      f"with {largest_count} penguins.")
print(f"The species with the least observations is {smallest_species} "
      f"with {smallest_count} penguins.")
print()

# Explore a species using a sentinel-controlled while loop
valid_selections = 0

print("Explore a species:")
species_choice = input("Enter Chinstrap, Gentoo, Adelie, or Done: ")

while species_choice != "Done":
    if species_choice not in species_names:
        print(species_choice, "is not one of the species in this dataset")
    else:
        # Determine the selected species
        valid_selections += 1

        if species_choice == species_names[0]:
            selected_index = 0
        elif species_choice == species_names[1]:
            selected_index = 1
        else:
            selected_index = 2

        selected_species = species_names[selected_index]
        selected_count = species_counts[selected_index]
        selected_percent = species_percentages[selected_index]

        # Classify the species
        if selected_percent < 25:
            size_category = "small"
        elif selected_percent < 40:
            size_category = "medium"
        else:
            size_category = "large"

        # Determine its position
        if (selected_species == largest_species) or \
                (selected_species == smallest_species):
            if selected_species == largest_species:
                position_description = "largest"
            else:
                position_description = "smallest"
        else:
            position_description = "middle sized"

        # Compare with the average
        average_position = "above" if selected_count > average_penguins else "below"

        # Print results only for a valid species
        print(f"{species_choice} has {selected_count} observations, "
              f"representing {selected_percent:.2f}% of the dataset.")
        print(f"{species_choice} is classified as a {size_category} species group.")
        print(f"{species_choice} is the {position_description} species group.")
        print(f"The penguin count is {average_position} average.")
        print(f"Its observation count is {average_position} the dataset "
              f"average of {average_penguins}")
        print()

    species_choice = input("Enter Chinstrap, Gentoo, Adelie, or Done: ")

# Display the final summary after the loop ends
print(f"You explored {valid_selections} valid species selections.")

